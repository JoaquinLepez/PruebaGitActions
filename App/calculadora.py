class Calculadora:
    
    @staticmethod
    def sumar(a: int, b: int) -> int:
        return a + b
    
    @staticmethod
    def restar(a: int, b: int) -> int:
        return a - b
    
    @staticmethod
    def multiplicar(a: int, b: int) -> int:
        return a * b
    
    @staticmethod
    def dividir(a:int, b:int) -> float:
        return a / b
